#!/usr/bin/env python3
"""Regenerate systems.js from a checkout of https://github.com/MustardOS/internal

Usage:
    git clone --depth 1 https://github.com/MustardOS/internal.git
    python3 tools/gen-systems.py path/to/internal > systems.js

Reads share/info/manifest/{libretro,external}.json (the same files muOS uses
to auto-assign cores to ROM folders) and config/system/version.
"""
