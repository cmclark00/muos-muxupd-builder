def pick_folder(name, friendly):
    preferred = PREFERRED_FOLDERS.get(name)
    if preferred:
        if preferred not in friendly:
            sys.exit(f"Preferred folder '{preferred}' is not a friendly name for '{name}'")
        return preferred
    # Shortest readable name wins; very short ones (ss, gw, ...) are too cryptic
    candidates = sorted(friendly, key=lambda f: (len(f) < 3, len(f), f))
    return candidates[0]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)

    root = Path(sys.argv[1])
    version = (root / "config/system/version").read_text(encoding="utf-8").strip()

    systems = {}
    for manifest in ("libretro", "external"):
        data = json.loads((root / f"share/info/manifest/{manifest}.json").read_text(encoding="utf-8"))
        for key, entry in data.items():
            system = systems.setdefault(key, {
                "name": entry.get("name") or key,
                "group": entry.get("namespace") or "Other",
                "catalogue": entry.get("catalogue") or key,
                "friendly": [],
                "bios": [],
            })
            for friendly in entry.get("friendly") or []:
                if friendly.lower() not in system["friendly"]:
                    system["friendly"].append(friendly.lower())
            for bios in entry.get("bios") or []:
                item = {"file": bios["file"], "md5": (bios.get("hash") or "").lower()}
                if item not in system["bios"]:
                    system["bios"].append(item)

    output = []
    for key in sorted(systems, key=str.lower):
        system = systems[key]
        if not system["friendly"]:
            continue
        system["folder"] = pick_folder(key, system["friendly"])
        output.append({
            "name": system["name"],
            "group": system["group"],
            "folder": system["folder"],
            "catalogue": system["catalogue"],
            "friendly": system["friendly"],
            "bios": system["bios"],
        })

    code, _, codename = version.partition("_")
    print("// Generated by tools/gen-systems.py from MustardOS/internal - do not edit by hand.")
    print(f"// Source version: {version}")
    print(f"const MUOS_VERSION = {json.dumps(code + ' ' + codename.title())};")
    print()
    print("const MUOS_SYSTEMS = [")
    for system in output:
        print(f"  {json.dumps(system, ensure_ascii=False)},")
    print("];")


if __name__ == "__main__":
    main()
